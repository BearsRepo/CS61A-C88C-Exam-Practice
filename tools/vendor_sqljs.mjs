// Builds app/vendor/sqljs/sql_bundle.js: SQLite compiled to WebAssembly (sql.js), as one plain script, so Run Code for
// SQL works both when the site is served and when index.html is opened from disk (a file:// page can't fetch() a
// .wasm file, but it can add a <script> tag).
//
//   node tools/vendor_sqljs.mjs
//
// Needs: an internet connection and `tar`.
//
// Safety: the package tarball is downloaded from the npm registry and must match BOTH the SHA-512 pinned below and
// the integrity value the registry publishes for this version; otherwise nothing is written.
//
// The bundle holds (window.CS61A_SQL_ASSETS):
//   version  the sql.js version
//   glue     dist/sql-wasm.js (defines initSqlJs; loaded inside the runner's worker)
//   wasm     dist/sql-wasm.wasm, base64
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '1.14.2';
// SHA-512 of sql.js-1.14.2.tgz, base64 (the npm "integrity" value). Update it together with VERSION.
const PINNED = 'sha512-3ZGPovObMFrdw79zrUHbfdE/DLIsy8jdNdssmMSQuRAymedU6q84asPt0kgiqrdMYlPegDItiIMfmIXzZnYFcw==';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'app', 'vendor', 'sqljs');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vendor-sqljs-'));

async function get(url, as) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return as === 'json' ? res.json() : Buffer.from(await res.arrayBuffer());
}

const meta = await get(`https://registry.npmjs.org/sql.js/${VERSION}`, 'json');
const tgz = await get(meta.dist.tarball);
const sha512 = 'sha512-' + crypto.createHash('sha512').update(tgz).digest('base64');
if (sha512 !== meta.dist.integrity) throw new Error(`Tarball does not match the registry's integrity value:\n  got      ${sha512}\n  registry ${meta.dist.integrity}`);
if (sha512 !== PINNED) throw new Error(`Tarball does not match the pinned hash:\n  got    ${sha512}\n  pinned ${PINNED}`);

fs.writeFileSync(path.join(tmp, 'pkg.tgz'), tgz);
execFileSync('tar', ['-xzf', 'pkg.tgz'], { cwd: tmp });
const dist = path.join(tmp, 'package', 'dist');
const glue = fs.readFileSync(path.join(dist, 'sql-wasm.js'), 'utf8');
const wasm = fs.readFileSync(path.join(dist, 'sql-wasm.wasm'));

fs.mkdirSync(outDir, { recursive: true });
const header = `// sql.js ${VERSION} (SQLite compiled to WebAssembly), https://github.com/sql-js/sql.js, MIT licence (see LICENSE).\n`
  + `// Generated by tools/vendor_sqljs.mjs from the npm tarball (${sha512}). Do not edit.\n`
  + `// wasm SHA-256: ${crypto.createHash('sha256').update(wasm).digest('hex')}\n`;
fs.writeFileSync(path.join(outDir, 'sql_bundle.js'),
  `${header}window.CS61A_SQL_ASSETS = ${JSON.stringify({ version: VERSION, glue, wasm: wasm.toString('base64') })};\n`);
fs.copyFileSync(path.join(tmp, 'package', 'LICENSE'), path.join(outDir, 'LICENSE'));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`Wrote app/vendor/sqljs/sql_bundle.js (${(fs.statSync(path.join(outDir, 'sql_bundle.js')).size / 1e6).toFixed(2)} MB) and LICENSE`);
